<#
  Start-E3D-GUI-Writable.ps1 - opens GRAPHICAL E3D for a project from config\projects.json
  (same launch parameters as Start-Nexus.ps1, without TTY) with NEXUS_READONLY=0 for this process only.

  Usage:  .\Start-E3D-GUI-Writable.ps1 -Project <code>
  (or default_gui_project in config\runtime.json)
  Nexus starts by itself (startup macro); with -NoAutoNexus run in the E3D command window the macro
  the script prints (run\<code>-gui\Start-Nexus-GUI.pmlmac, generated with the current DLL path).
  The password comes from the Windows Credential Manager if stored (scripts\set-e3d-login.ps1 in the repo).
  The repo (for mcp\credstore.py) is $env:NEXUS_REPO, or "repo" in config\runtime.json, or ..\AVEVA_Nexus.
  Use it only with a test MDB: any PML sent through Nexus can change the model.
#>
param(
    [string]$Project,
    [switch]$Prompt,       # ask for the password even if one is stored
    [switch]$NoAutoNexus,  # do not start Nexus by itself (then run the generated Start-Nexus-GUI.pmlmac by hand)
    [switch]$UiDispatch    # NEXUS_UI_DISPATCH=1: Nexus runs E3D work on the E3D user-interface thread (test of the GUI hang)
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
. (Join-Path $root 'NexusRuntime.ps1')
$all = Get-Content (Join-Path $root 'config\projects.json') -Raw | ConvertFrom-Json
if (-not $Project) {
    $rc = Join-Path $root 'config\runtime.json'
    if (Test-Path $rc) { $Project = (Get-Content $rc -Raw | ConvertFrom-Json).default_gui_project }
}
if (-not $Project) { throw 'Pass -Project <code> (or set default_gui_project in config\runtime.json)' }
$cfg = $all.$Project
if (-not $cfg) { throw "Project '$Project' not found in config\projects.json" }
$port = if ($cfg.port) { [int]$cfg.port } else { 5001 }

# Login: Windows auth; else the password stored in the Windows Credential Manager by the Nexus MCP
# (scripts\set-e3d-login.ps1); else ask in the console (hidden input).
$plain = $null
if ($cfg.auth -eq 'windows') {
    $userPass = $cfg.user
} else {
    $mcpDir = Join-Path (Get-NexusRepoDir $root) 'mcp'
    if (-not $Prompt -and (Test-Path "$mcpDir\credstore.py")) {
        Push-Location $mcpDir
        try { $plain = uv run python -c "import sys, credstore; p = credstore.read(sys.argv[1], sys.argv[2]); sys.stdout.write(p or '')" $cfg.project $cfg.user } catch { $plain = $null }
        Pop-Location
    }
    if (-not $plain) {
        # Get-Credential fails with "Access is denied" from a .bat console here, so ask in the console.
        Write-Host "E3D login for $Project ($($cfg.project) $($cfg.mdb)), user $($cfg.user)"
        $secure = Read-Host -AsSecureString "Password"
        $plain = (New-Object System.Net.NetworkCredential('', $secure)).Password
    }
    if (-not $plain) { throw 'Login cancelled (empty password)' }
    $userPass = "$($cfg.user)/$plain"
}

# Generated macros (the DLL path is resolved now from current.txt): the one that starts Nexus, and the startup macro.
$addin = Get-NexusAddinPath $root
$runDir = Join-Path $root "run\$Project-gui"
New-Item -ItemType Directory -Force $runDir | Out-Null
$nexusMacro = Join-Path $runDir 'Start-Nexus-GUI.pmlmac'
@"
-- Start Nexus inside a graphical E3D session (Design). Generated by Start-E3D-GUI-Writable.ps1; do not edit.
-- Nexus then answers on http://localhost:$port/ with the login of THIS session (nothing is asked).
-- It is READ-ONLY unless the E3D process was started with the environment variable NEXUS_READONLY=0.
-- Do not run it while a TTY session (start_e3d) is up on the same port.
import '$addin'
handle any
endhandle
using namespace 'AVEVA_Nexus.Config'
!!nexusHost = object HostConfig()
!!nexusHost.SetPrefix('http://localhost:$port/')
!!nexusHost.Start()
handle any
  `$P NEXUS ERROR: it did not start (port $port in use, or the DLL could not be loaded). Details: `$!!error.text
  return
endhandle
!!nexusMode = !!nexusHost.DispatchMode()
`$P Nexus started on http://localhost:$port/  - E3D calls run in mode: `$!!nexusMode
"@ | Set-Content $nexusMacro -Encoding ASCII
Copy-Item (Join-Path $root 'Stop-Nexus-GUI.pmlmac') $runDir -Force

# Startup macro: enter the module and start Nexus, so nothing has to be typed in E3D.
$macro = Join-Path $runDir 'gui-session.pmlmac'
@"
$($cfg.module)
`$M/$nexusMacro
"@ | Set-Content $macro -Encoding ASCII
$last = if ($NoAutoNexus) { $cfg.module } else { "`$M/$macro" }

$launchArgs = @($cfg.product, $cfg.module3d, 'init', "`"$($cfg.init)`"", $cfg.project, $userPass, $cfg.mdb, $last)
$ui = if ($UiDispatch) { 'set NEXUS_UI_DISPATCH=1&& ' } else { '' }
# Launched through WMI (detached), with the environment on the cmd line: a WMI process does not inherit it.
$cmd = "cmd /c set NEXUS_READONLY=0&& $ui`"$($cfg.mon)`" $($launchArgs -join ' ')"
$r = Invoke-CimMethod -ClassName Win32_Process -MethodName Create -Arguments @{ CommandLine = $cmd; CurrentDirectory = (Split-Path $cfg.mon) }
$plain = $null; $userPass = $null; $cmd = $null
if ($r.ReturnValue -ne 0) { throw "WMI Create failed (code $($r.ReturnValue))" }
"Launched graphical E3D for $Project with NEXUS_READONLY=0" + $(if ($UiDispatch) { ' and NEXUS_UI_DISPATCH=1' } else { '' }) + $(if ($NoAutoNexus) { "; to start Nexus run in E3D: `$M/$nexusMacro" } else { "; Nexus starts by itself on port $port" })
